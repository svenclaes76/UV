"""Write requirements-lock.txt: every runtime package, direct and transitive,
pinned to one version for production (SR7, docs/security-review.md).

requirements.txt pins only what the app imports; the packages those pull in
(Streamlit's starlette/pyarrow/…, cryptography's cffi, …) would otherwise be
whatever is newest on the day the server installs. The lock is resolved for
the production target (Linux x86_64, Python 3.12) from any machine, without
installing anything:

    python tools/lock_requirements.py            # rewrite requirements-lock.txt
    python tools/lock_requirements.py --check    # exit 1 if it no longer matches requirements.txt

Production installs with `pip install -r requirements-lock.txt`
(docs/deployment.md); CI audits the same file with pip-audit
(.github/workflows/audit.yml). Run it after changing requirements.txt.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "requirements.txt"
LOCK = ROOT / "requirements-lock.txt"
PYTHON = "3.12"
PLATFORMS = ("manylinux_2_28_x86_64", "manylinux_2_17_x86_64", "manylinux2014_x86_64", "linux_x86_64")
# Resolved on the machine running this script, but only needed there.
_HOST_ONLY = {"colorama": 'sys_platform == "win32"'}

HEADER = """\
# Production pins: every runtime package, direct and transitive (SR7).
# Generated by tools/lock_requirements.py for Linux x86_64, Python {python},
# from the runtime section of requirements.txt. Don't edit by hand: change
# requirements.txt, then run `python tools/lock_requirements.py`.
"""


def runtime_requirements() -> list[str]:
    """requirements.txt lines above the "Dev/test" section, comments stripped."""
    out = []
    for line in REQUIREMENTS.read_text(encoding="utf-8").splitlines():
        if "Dev/test" in line:
            break
        line = line.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return out


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def resolve() -> list[tuple[str, str]]:
    with tempfile.TemporaryDirectory() as tmp:
        req = Path(tmp) / "req.txt"
        req.write_text("\n".join(runtime_requirements()) + "\n", encoding="utf-8")
        report = Path(tmp) / "report.json"
        cmd = [sys.executable, "-m", "pip", "install", "--quiet", "--dry-run", "--ignore-installed",
               "--report", str(report), "--python-version", PYTHON, "--only-binary=:all:",
               "--target", str(Path(tmp) / "t"), "-r", str(req)]
        for p in PLATFORMS + ("any",):
            cmd += ["--platform", p]
        subprocess.run(cmd, check=True)
        data = json.loads(report.read_text(encoding="utf-8"))
    pins = [(i["metadata"]["name"], i["metadata"]["version"]) for i in data["install"]]
    return sorted(pins, key=lambda p: _norm(p[0]))


def render(pins: list[tuple[str, str]]) -> str:
    lines = [HEADER.format(python=PYTHON)]
    for name, version in pins:
        marker = _HOST_ONLY.get(_norm(name))
        lines.append(f"{name}=={version}" + (f" ; {marker}" if marker else ""))
    return "\n".join(lines) + "\n"


def lock_pins(text: str) -> dict[str, str]:
    pins = {}
    for line in text.splitlines():
        m = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s;]+)", line)
        if m:
            pins[_norm(m.group(1))] = m.group(2)
    return pins


def mismatches() -> list[str]:
    """Direct requirements whose pin is missing from, or different in, the lock."""
    locked = lock_pins(LOCK.read_text(encoding="utf-8")) if LOCK.exists() else {}
    out = []
    for req in runtime_requirements():
        name, _, version = req.partition("==")
        if locked.get(_norm(name)) != version:
            out.append(f"{req} (lock: {locked.get(_norm(name), 'missing')})")
    return out


def main(argv: list[str]) -> int:
    if "--check" in argv:
        bad = mismatches()
        for b in bad:
            print("out of date:", b)
        return 1 if bad else 0
    LOCK.write_text(render(resolve()), encoding="utf-8")
    print(f"wrote {LOCK.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
