"""The Consensus logo files in assets/logo/ (docs/design/logo-consensus-spec.md),
generated by tools/build_logo.py."""
import re
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
LOGO = ROOT / "assets" / "logo"

ASSETS = [
    "uvalu-mark.svg", "uvalu-mark-light.svg", "uvalu-mark-mono.svg",
    "uvalu-mark-small.svg", "uvalu-mark-small-mono.svg",
    "uvalu-lockup-dark.svg", "uvalu-lockup-light.svg", "uvalu-lockup-mono.svg",
    "favicon.ico", "uvalu-mark-small-32.png", "apple-touch-icon.png",
    "icon-192.png", "icon-512.png", "uvalu-mark-512.png", "og-image.png",
]
SVGS = [n for n in ASSETS if n.endswith(".svg")]
# Spec, Geometry: ring centres, radius, stroke width per weight.
MAIN = {"cx": {"22", "42"}, "r": "17", "stroke": "4.5"}
SMALL = {"cx": {"24", "40"}, "r": "18", "stroke": "5.5"}
LIGHT_GROUND = ["uvalu-mark-light.svg", "uvalu-lockup-light.svg"]
NS = "{http://www.w3.org/2000/svg}"


@pytest.mark.parametrize("name", ASSETS)
def test_every_asset_in_the_spec_table_exists(name):
    assert (LOGO / name).is_file() and (LOGO / name).stat().st_size > 0


@pytest.mark.parametrize("name", SVGS)
def test_rings_follow_the_spec_geometry(name):
    geom = SMALL if "small" in name else MAIN
    circles = list(ET.parse(LOGO / name).getroot().iter(f"{NS}circle"))
    assert len(circles) == 2
    assert {c.get("cx") for c in circles} == geom["cx"]
    assert {c.get("cy") for c in circles} == {"32"}
    assert {c.get("r") for c in circles} == {geom["r"]}
    assert {c.get("stroke-width") for c in circles} == {geom["stroke"]}
    assert {c.get("fill") for c in circles} == {"none"}


@pytest.mark.parametrize("name", SVGS)
def test_lens_is_drawn_before_the_rings(name):
    root = ET.parse(LOGO / name).getroot()
    shapes = [el.tag.replace(NS, "") for el in root.iter() if el.tag in (f"{NS}path", f"{NS}circle")]
    assert shapes[:3] == ["path", "circle", "circle"]


@pytest.mark.parametrize("name", SVGS)
def test_no_live_text(name):
    """The wordmark is outlined, so the logo never depends on Inter being installed."""
    assert "<text" not in (LOGO / name).read_text(encoding="utf-8")


@pytest.mark.parametrize("name", LIGHT_GROUND)
def test_no_mint_on_a_light_ground(name):
    assert "#1DD6A4" not in (LOGO / name).read_text(encoding="utf-8").upper()


def test_lockups_carry_the_wordmark_with_the_accented_final_u():
    for name, accent in (("uvalu-lockup-dark.svg", "#1DD6A4"), ("uvalu-lockup-light.svg", "#1A8C6E")):
        fills = re.findall(r'<path d="[^"]+" fill="([^"]+)"', (LOGO / name).read_text(encoding="utf-8"))
        # lens, then the five letters u-v-a-l-u; only the lens and the last u carry the accent
        assert len(fills) == 6 and fills[0] == accent and fills[-1] == accent
        assert accent not in fills[1:-1]


def test_svgs_are_up_to_date_with_the_builder():
    """Nobody edits an SVG by hand: tools/build_logo.py regenerates them."""
    pytest.importorskip("fontTools")
    import importlib.util
    spec = importlib.util.spec_from_file_location("build_logo", ROOT / "tools" / "build_logo.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    for name, text in mod.svg_files().items():
        assert (LOGO / name).read_text(encoding="utf-8") == text, name


def test_favicon_has_three_sizes():
    from PIL import Image
    assert Image.open(LOGO / "favicon.ico").info["sizes"] == {(16, 16), (32, 32), (48, 48)}
