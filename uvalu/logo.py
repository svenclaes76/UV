"""The Uvalu lockup (Consensus mark + outlined wordmark) as inline SVG.

The markup comes from ``assets/logo/uvalu-lockup-dark.svg``, generated by
``tools/build_logo.py`` from ``docs/design/logo-consensus-spec.md``; this
module never draws or recolours the logo itself. Inline SVG rather than an
<img>: it sits in one flex row with the "value engine" / "admin" tag, and the
top bar's colours follow the theme through two tokens.

``theme_tokens=True`` (top bar) maps the dark lockup's two inks to
``var(--logo-ring)`` and ``var(--logo-accent)``. With the light theme's token
values (``#0D1F3C``, ``#1A8C6E``, uvalu/styles.py) the result is exactly
``uvalu-lockup-light.svg``; with the dark values, ``uvalu-lockup-dark.svg``
(decided 11 Oct 2026: light lockup in the light theme). ``theme_tokens=False``
keeps the dark lockup's own colours, for the dark-only Admin portal and
sign-in panel.
"""
from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path

LOCKUP_DARK = Path(__file__).resolve().parent.parent / "assets" / "logo" / "uvalu-lockup-dark.svg"
GRID = 64                       # the mark's grid: rendered height = mark height
RING_DARK, ACCENT_DARK = "#FFFFFF", "#1DD6A4"


@lru_cache(maxsize=1)
def _lockup() -> "tuple[float, str]":
    """(viewBox width, inner markup) of the dark lockup."""
    text = LOCKUP_DARK.read_text(encoding="utf-8")
    view_w = float(re.search(r'viewBox="0 0 ([0-9.]+) ', text).group(1))
    inner = text.split(">", 1)[1].rsplit("</svg>", 1)[0]
    return view_w, inner


def lockup_svg(height: float, *, theme_tokens: bool) -> str:
    """The lockup at a mark height of ``height`` px."""
    view_w, inner = _lockup()
    if theme_tokens:
        inner = (inner.replace(f'"{RING_DARK}"', '"var(--logo-ring)"')
                      .replace(f'"{ACCENT_DARK}"', '"var(--logo-accent)"'))
    width = round(height * view_w / GRID, 2)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {view_w:g} {GRID}" '
            f'height="{height:g}" width="{width:g}" role="img" aria-label="Uvalu" '
            f'style="display:block;flex:none;overflow:visible;">{inner}</svg>')
